/**
 * True if [codepoint] is written right to left.
 *
 * Binary search over [RTL_RANGES]; the table is sorted and non-overlapping by construction.
 */
fun isRightToLeft(codepoint: Int): Boolean {
  var low = 0
  var high = RTL_RANGES.size / 2 - 1
  while (low <= high) {
    val mid = (low + high) / 2
    val start = RTL_RANGES[mid * 2]
    val end = RTL_RANGES[mid * 2 + 1]
    when {
      codepoint < start -> high = mid - 1
      codepoint > end -> low = mid + 1
      else -> return true
    }
  }
  return false
}
